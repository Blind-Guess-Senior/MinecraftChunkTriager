"""Versioned id vocabularies.

Feature columns are indexed by these lists, so a model trained on one world
lines up with any other world of the same version. Files are generated by
``scripts/gen_vocab.py`` and must not be edited by hand.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path

DATA_DIR = Path(__file__).parent / "data"


@dataclass(frozen=True)
class Vocabulary:
    hash: str
    blocks: tuple[str, ...]
    biomes: tuple[str, ...]
    entities: tuple[str, ...]
    block_entities: tuple[str, ...]
    structures: tuple[str, ...]
    surface_blocks: frozenset[str]
    air_blocks: frozenset[str]


def index(names: tuple[str, ...]) -> dict[str, int]:
    return {name: i for i, name in enumerate(names)}


@cache
def load_vocabulary(name: str) -> Vocabulary:
    doc = json.loads((DATA_DIR / f"{name}.json").read_text(encoding="utf-8"))
    return Vocabulary(
        hash=doc["hash"],
        blocks=tuple(doc["blocks"]),
        biomes=tuple(doc["biomes"]),
        entities=tuple(doc["entities"]),
        block_entities=tuple(doc["block_entities"]),
        structures=tuple(doc["structures"]),
        surface_blocks=frozenset(doc["surface_blocks"]),
        air_blocks=frozenset(doc["air_blocks"]),
    )
